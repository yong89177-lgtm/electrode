#!/bin/bash
# Mac/Linux용 - 더블클릭(또는 "터미널에서 열기") 한 번으로 설치+실행까지 자동으로 처리한다.
cd "$(dirname "$0")"

echo "============================================"
echo " MAPS 서버 시작 준비 중..."
echo "============================================"

npm config set strict-ssl false >/dev/null 2>&1

echo "필요한 패키지를 확인/설치합니다 (몇 분 걸릴 수 있어요)..."
if ! npm install; then
  echo ""
  echo "[오류] 패키지 설치에 실패했습니다. 위에 나온 메시지를 캡처해서 문의해주세요."
  read -p "엔터를 누르면 창이 닫힙니다..."
  exit 1
fi

if [ ! -f .env ]; then
  cat > .env <<'EOF'
ADMIN_PASSWORD=maps1234
PORT=8081
EOF
  echo ""
  echo "================================================================"
  echo " 최초 실행이라 관리자 비밀번호를 기본값(maps1234)으로 설정했습니다."
  echo " 로그인 후 꼭 비밀번호를 바꾸시거나, 지금 이 창을 닫고 이 폴더의"
  echo " .env 파일을 텍스트 편집기로 열어 원하는 값으로 바꾼 뒤 다시 실행하세요."
  echo "================================================================"
  echo ""
  read -p "엔터를 누르면 서버를 시작합니다..."
fi

echo ""
echo "MAPS 서버를 시작합니다. 이 창을 닫으면 서버가 꺼집니다."
echo ""
npm start
